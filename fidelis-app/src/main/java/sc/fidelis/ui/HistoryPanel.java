/**
 * History and macro (docs D12 UI-10): one row per record with origin and provenance badges, the
 * macro generated by the engine from the history (read-only), export to .ijm, replay, and
 * undo/redo (direct operations on the focused document).
 */
public final class HistoryPanel extends JPanel {
    private static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("HH:mm:ss").withZone(ZoneId.systemDefault());
    private static final Set<String> SESSION_OPS = Set.of(Operations.OPEN, Operations.SAVE_AS, Operations.CLOSE, Operations.NEW_IMAGE);

    private final UiContext ctx;
    private final List<HistoryRecord> records = new ArrayList<>();
    private final DefaultTableModel model = new DefaultTableModel(new String[] {"Time", "Origin", "Provenance", "Step", "Parameters", "Outcome"}, 0) {
        @Override
        public boolean isCellEditable(int r, int c) {
            return false;
        }
    };
    private final JTable table = new JTable(model);
    private final JTextArea macro = new JTextArea();
    private final JButton undo = new JButton("Undo");
    private final JButton redo = new JButton("Redo");
    private final JButton replay = new JButton("Replay");
    private final JButton export = new JButton("Export .ijm…");
    private final JButton edit = new JButton("Open in editor");

    HistoryPanel(UiContext ctx) {
        super(new BorderLayout());
        this.ctx = ctx;
        JPanel bar = new JPanel(new FlowLayout(FlowLayout.LEFT, 6, 4));
        undo.setToolTipText("Undo the last change to the focused image");
        redo.setToolTipText("Redo");
        replay.setToolTipText("Run the selected steps (or all steps) again, in order; confirmations still apply");
        export.setToolTipText("Save the generated macro as an .ijm file");
        undo.addActionListener(e -> direct(Operations.UNDO, "Undo"));
        redo.addActionListener(e -> direct(Operations.REDO, "Redo"));
        replay.addActionListener(e -> replay());
        export.addActionListener(e -> exportMacro());
        edit.setToolTipText("Open the generated macro in the Macro editor, where it can be changed and run");
        edit.addActionListener(e -> {
            ctx.editor().setText(ctx.engine.exportMacro());
            ctx.docks().showEditor();
        });
        bar.add(undo);
        bar.add(redo);
        bar.add(replay);
        bar.add(export);
        bar.add(edit);
        add(bar, BorderLayout.NORTH);

        table.setShowGrid(false);
        table.setAutoResizeMode(JTable.AUTO_RESIZE_LAST_COLUMN);
        // Time, Origin, Provenance and Outcome keep a width that shows their whole text in the demo layout (issue #15);
        // Step and Parameters take what remains (the full parameter text is in the tooltip).
        int[] widths = {66, 44, 86, 150, 200, 64};
        int[] minimums = {62, 40, 80, 90, 60, 56};
        for (int i = 0; i < widths.length; i++) {
            table.getColumnModel().getColumn(i).setPreferredWidth(widths[i]);
            table.getColumnModel().getColumn(i).setMinWidth(minimums[i]);
        }
        table.getColumnModel().getColumn(0).setMaxWidth(72);
        table.getColumnModel().getColumn(1).setMaxWidth(48);
        table.getColumnModel().getColumn(2).setMaxWidth(110);
        table.getColumnModel().getColumn(5).setMaxWidth(90);
        table.getColumnModel().getColumn(4).setCellRenderer(new TooltipRenderer());
        table.getColumnModel().getColumn(1).setCellRenderer(new OriginRenderer());
        table.getColumnModel().getColumn(2).setCellRenderer(new BadgeRenderer());
        table.getSelectionModel().addListSelectionListener(e -> updateButtons());
        JScrollPane left = new JScrollPane(table);
        left.setBorder(BorderFactory.createMatteBorder(1, 0, 0, 1, Theme.panelBorder()));

        macro.setEditable(false);
        macro.setFont(new Font(Font.MONOSPACED, Font.PLAIN, 12));
        macro.setBorder(BorderFactory.createEmptyBorder(4, 6, 4, 6));
        JPanel right = new JPanel(new BorderLayout());
        JLabel l = new JLabel("Macro generated from history (read-only)");
        l.setBorder(BorderFactory.createEmptyBorder(3, 6, 3, 6));
        l.setForeground(Theme.muted());
        right.add(l, BorderLayout.NORTH);
        JScrollPane rs = new JScrollPane(macro);
        rs.setBorder(BorderFactory.createMatteBorder(1, 0, 0, 0, Theme.panelBorder()));
        right.add(rs, BorderLayout.CENTER);

        JSplitPane split = new JSplitPane(JSplitPane.HORIZONTAL_SPLIT, left, right);
        split.setResizeWeight(0.68);
        split.setOneTouchExpandable(true); // the macro text can be tucked away when the step list needs the width
        split.setBorder(null);
        right.setMinimumSize(new java.awt.Dimension(0, 0));
        add(split, BorderLayout.CENTER);
        reload();
    }

    /** Re-read the whole history and the generated macro from the engine. */
    void reload() {
        records.clear();
        records.addAll(ctx.engine.history());
        model.setRowCount(0);
        for (HistoryRecord r : records) model.addRow(row(r));
        macro.setText(records.isEmpty() ? "// No steps yet." : ctx.engine.exportMacro());
        macro.setCaretPosition(0);
        if (!records.isEmpty()) table.scrollRectToVisible(table.getCellRect(records.size() - 1, 0, true));
        updateButtons();
    }

    private static Object[] row(HistoryRecord r) {
        return new Object[] {TIME.format(r.time()), r.origin(), r.provenance(), r.label(), summary(r.params()),
            r.outcome() == OperationState.COMPLETED ? "ok" : r.outcome().toString().toLowerCase(java.util.Locale.ROOT)};
    }

    static String summary(Map<String, Object> params) {
        if (params == null || params.isEmpty()) return "";
        StringBuilder sb = new StringBuilder();
        for (Map.Entry<String, Object> e : params.entrySet()) {
            if (sb.length() > 0) sb.append(", ");
            Object v = e.getValue();
            if (v instanceof sc.fidelis.engine.api.RoiGeometry g) {
                sb.append(e.getKey()).append('=').append(g.type().toLowerCase(java.util.Locale.ROOT));
                if (g.bounds() != null) sb.append(java.util.Arrays.toString(g.bounds()).replace('[', '(').replace(']', ')'));
                continue;
            }
            String s = v instanceof Double d && d == Math.rint(d) && Math.abs(d) < 1e9 ? Long.toString(d.longValue()) : String.valueOf(v);
            sb.append(e.getKey()).append('=').append(s);
        }
        return sb.toString();
    }

    private void updateButtons() {
        boolean ready = ctx.engine.state() == sc.fidelis.engine.api.Enums.EngineState.READY;
        boolean doc = ctx.focusedId() != null;
        undo.setEnabled(ready && doc);
        redo.setEnabled(ready && doc);
        replay.setEnabled(ready && !records.isEmpty());
        export.setEnabled(!records.isEmpty());
    }

    private void direct(String op, String label) {
        if (ctx.focusedId() == null) return;
        ctx.submit(ActionRequest.direct(Origin.PANEL, op, Map.of(), ctx.target()), label);
    }

    private void exportMacro() {
        JFileChooser fc = new JFileChooser();
        fc.setDialogTitle("Export macro");
        fc.setSelectedFile(new java.io.File("fidelis-session.ijm"));
        if (fc.showSaveDialog(ctx.frame) != JFileChooser.APPROVE_OPTION) return;
        java.io.File f = fc.getSelectedFile();
        if (f.exists() && javax.swing.JOptionPane.showConfirmDialog(ctx.frame, f.getName() + " exists. Overwrite it?", "Export macro",
                javax.swing.JOptionPane.OK_CANCEL_OPTION, javax.swing.JOptionPane.WARNING_MESSAGE) != javax.swing.JOptionPane.OK_OPTION) return;
        try {
            Files.writeString(f.toPath(), ctx.engine.exportMacro(), StandardCharsets.UTF_8);
            ctx.notice("Exported macro to " + f, false);
        } catch (IOException ex) {
            ctx.notice("Export failed: " + ex.getMessage(), true);
        }
    }

    /** Request that repeats a history record, or null when it cannot be replayed (observed native steps). */
    static ActionRequest replayRequest(HistoryRecord r) {
        if (r.outcome() != OperationState.COMPLETED || r.commandId() == null) return null;
        String id = r.commandId();
        boolean command = id.matches("ij[0-9a-z]*:.*");
        ActionKind kind = command ? ActionKind.COMMAND : SESSION_OPS.contains(id) ? ActionKind.SESSION : ActionKind.DIRECT;
        return new ActionRequest(UUID.randomUUID().toString(), Origin.REPLAY, kind, command ? id : null, command ? null : id,
                r.params(), r.target(), null, r.actionId());
    }

    private void replay() {
        int[] sel = table.getSelectedRows();
        List<HistoryRecord> steps = new ArrayList<>();
        if (sel.length == 0) steps.addAll(records);
        else for (int i : sel) steps.add(records.get(table.convertRowIndexToModel(i)));
        List<ActionRequest> reqs = new ArrayList<>();
        for (HistoryRecord r : steps) {
            ActionRequest q = replayRequest(r);
            if (q == null) ctx.notice("Skipped " + r.label() + ": it cannot be replayed (" + r.provenance() + ")", false);
            else reqs.add(q);
        }
        if (reqs.isEmpty()) return;
        CompletableFuture<Boolean> chain = CompletableFuture.completedFuture(true);
        for (ActionRequest q : reqs) {
            chain = chain.thenCompose(ok -> {
                if (!ok) return CompletableFuture.completedFuture(false);
                CompletableFuture<ActionResult> f = ctx.submit(q, "Replay " + (q.commandId() != null ? q.commandId().substring(q.commandId().lastIndexOf('>') + 1) : q.operation()));
                return f.thenApply(res -> res.state() == OperationState.COMPLETED);
            });
        }
    }

    void handle(EngineEvent e) {
        if (e instanceof EngineEvent.HistoryAppended || e instanceof EngineEvent.EngineStateChanged
                || e instanceof EngineEvent.DocumentFocusChanged) reload();
    }

    int rowCount() {
        return model.getRowCount();
    }

    String macroText() {
        return macro.getText();
    }

    // ---- renderers ----------------------------------------------------------------------------

    /** Plain text cell whose tooltip carries the full value (parameters are often wider than the column). */
    private static final class TooltipRenderer extends DefaultTableCellRenderer {
        @Override
        public Component getTableCellRendererComponent(JTable t, Object v, boolean sel, boolean focus, int r, int c) {
            super.getTableCellRendererComponent(t, v, sel, focus, r, c);
            String s = v == null ? "" : v.toString();
            setToolTipText(s.isEmpty() ? null : s);
            return this;
        }
    }

    /** Origin as a small lettered chip: M enu, S earch, K shortcut, C anvas, P anel, T yped NL, V oice, m acro, R eplay, O bserved. */
    private static final class OriginRenderer extends DefaultTableCellRenderer {
        @Override
        public Component getTableCellRendererComponent(JTable t, Object v, boolean sel, boolean focus, int r, int c) {
            super.getTableCellRendererComponent(t, "", sel, focus, r, c);
            Origin o = (Origin) v;
            String letter = switch (o) {
                case MENU -> "M";
                case SEARCH -> "S";
                case SHORTCUT -> "K";
                case CANVAS -> "C";
                case PANEL -> "P";
                case NL_TYPED -> "T";
                case NL_SPOKEN -> "V";
                case MACRO -> "m";
                case REPLAY -> "R";
                case OBSERVED -> "O";
            };
            setText(letter);
            setHorizontalAlignment(SwingConstants.CENTER);
            setFont(getFont().deriveFont(Font.BOLD));
            setToolTipText(o.name().toLowerCase(java.util.Locale.ROOT).replace('_', ' '));
            return this;
        }
    }

    /** Provenance as a coloured text badge: never colour alone (D11 A-05). */
    private static final class BadgeRenderer extends DefaultTableCellRenderer {
        @Override
        public Component getTableCellRendererComponent(JTable t, Object v, boolean sel, boolean focus, int r, int c) {
            super.getTableCellRendererComponent(t, "", sel, focus, r, c);
            Provenance p = (Provenance) v;
            String text = switch (p) {
                case NATIVE -> "NATIVE";
                case TYPED -> "TYPED";
                case LEGACY_DIALOG -> "LEGACY";
                case UNRECORDABLE -> "UNRECORDABLE";
            };
            Color color = switch (p) {
                case NATIVE -> Theme.isDark() ? new Color(0x7fb0ff) : new Color(0x2f6fdb);
                case TYPED -> Theme.isDark() ? new Color(0x6fd08a) : new Color(0x2a8a4a);
                case LEGACY_DIALOG -> Theme.isDark() ? new Color(0xf0b440) : new Color(0xb07400);
                case UNRECORDABLE -> Theme.isDark() ? new Color(0xff7b7b) : new Color(0xc0262d);
            };
            setText(text);
            setFont(getFont().deriveFont(Font.BOLD, 11f));
            if (!sel) setForeground(color);
            setToolTipText(switch (p) {
                case NATIVE -> "Handled directly by Fiji and observed";
                case TYPED -> "Typed command with complete parameters; exact macro form";
                case LEGACY_DIALOG -> "Ran through an original Fiji dialog; parameters only if visible";
                case UNRECORDABLE -> "Cannot be recorded or replayed faithfully";
            });
            return this;
        }
    }
}
